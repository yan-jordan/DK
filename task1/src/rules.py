"""
rules.py — قواعد اتمیک محاسبه‌ی هزینه‌ی ارسال.

هر تابع این ماژول «خالص» (pure) است: ورودی ساده می‌گیرد، خروجی ساده می‌دهد،
هیچ I/O ای ندارد و هیچ حالتی را تغییر نمی‌دهد. به همین دلیل مستقیماً و بدون
هیچ mock ای قابل تست است.

هر تابع/ثابت به بند متناظرش در DECISIONS.md ارجاع داده شده است.
"""

from __future__ import annotations

import math
from datetime import datetime, timedelta, timezone

# ---------------------------------------------------------------------------
# منطقه‌ی زمانی مرجع کسب‌وکار — بند ۱۰ DECISIONS.md
# ---------------------------------------------------------------------------
# ایران از سال ۱۴۰۱ ساعت تابستانی را حذف کرده، پس آفست ثابت +03:30 است.
# با این حال از zoneinfo استفاده می‌کنیم تا اگر روزی قانون عوض شد، پایگاه‌داده‌ی
# tz به‌صورت خودکار درست عمل کند؛ و اگر tzdata روی سیستم نبود، به آفست ثابت
# سقوط می‌کنیم تا اجرای برنامه هرگز به‌خاطر نبود یک وابستگی سیستمی نشکند.
try:  # pragma: no cover - مسیر وابسته به محیط
    from zoneinfo import ZoneInfo

    BUSINESS_TZ = ZoneInfo("Asia/Tehran")
except Exception:  # pragma: no cover - مسیر وابسته به محیط
    BUSINESS_TZ = timezone(timedelta(hours=3, minutes=30), name="Asia/Tehran")


# ---------------------------------------------------------------------------
# ثابت‌های قواعد (هیچ عدد جادویی‌ای نباید داخل بدنه‌ی توابع تکرار شود)
# ---------------------------------------------------------------------------

# قاعده‌ی ۱ — هزینه‌ی پایه بر اساس مقصد
BASE_FEE_BY_CITY_TIER: dict[str, int] = {
    "tehran": 25_000,
    "provincial_capital": 35_000,
}
DEFAULT_BASE_FEE = 50_000  # «سایر شهرها»

# قاعده‌ی ۳ — هزینه‌ی وزن اضافه
WEIGHT_ALLOWANCE_GRAMS = 1_000  # تا ۱ کیلوگرم رایگان
WEIGHT_STEP_GRAMS = 500  # به ازای هر ۵۰۰ گرم (یا کسری از آن)
WEIGHT_STEP_FEE = 5_000

# قاعده‌ی ۵ — آستانه‌ی ارسال رایگان بر اساس مبلغ سفارش
FREE_SHIPPING_AMOUNT_THRESHOLD = 500_000

# قاعده‌ی ۶ — هزینه‌ی ثابت مرسوله‌ی حجیم
BULKY_FLAT_FEE = 150_000

# قاعده‌ی ۷ — افزایش شبانه
NIGHT_START_HOUR = 23  # شامل
NIGHT_END_HOUR = 6  # غیرشامل
NIGHT_SURCHARGE_MULTIPLIER = 1.1

# قاعده‌ی ۸ — کارمزد پرداخت در محل
CASH_ON_DELIVERY_FEE = 10_000
ONLINE_PAYMENT_METHOD = "online"

# قاعده‌ی ۹ — سقف هزینه‌ی ارسال هر سفارش
ORDER_SHIPPING_FEE_CAP = 200_000

# قاعده‌ی ۴ — عضویت پلاس
PLUS_MEMBERSHIP = "plus"


# ---------------------------------------------------------------------------
# قاعده‌ی ۱ — هزینه‌ی پایه بر اساس مقصد
# ---------------------------------------------------------------------------
def base_fee_for_city_tier(city_tier: str) -> int:
    """
    هزینه‌ی پایه‌ی مقصد را برمی‌گرداند.

    تصمیم (بند ۸ DECISIONS.md): مبنا فیلد ساختاریافته‌ی `city_tier` است، نه
    `destination_city`. در ORD-1021 این دو با هم متناقض‌اند («تهران» با tier
    «other») و ما به `city_tier` تکیه می‌کنیم.

    هر مقدار ناشناخته‌ای (نه tehran و نه provincial_capital) به‌صورت
    محافظه‌کارانه «سایر شهرها» فرض می‌شود — بند ۱۲ DECISIONS.md.
    """
    return BASE_FEE_BY_CITY_TIER.get(city_tier, DEFAULT_BASE_FEE)


# ---------------------------------------------------------------------------
# قاعده‌ی ۳ — هزینه‌ی وزن
# ---------------------------------------------------------------------------
def weight_fee(total_weight_grams: int) -> int:
    """
    به ازای هر ۵۰۰ گرم (یا کسری از آن) بالای ۱ کیلوگرم، ۵٬۰۰۰ تومان.

    `max(0, ...)` از تولید هزینه‌ی منفی برای مرسوله‌های زیر ۱ کیلو جلوگیری می‌کند
    و `ceil` تضمین می‌کند هر کسری از ۵۰۰ گرم یک پله‌ی کامل حساب شود.
    """
    extra = max(0, total_weight_grams - WEIGHT_ALLOWANCE_GRAMS)
    steps = math.ceil(extra / WEIGHT_STEP_GRAMS)
    return steps * WEIGHT_STEP_FEE


def item_total_weight_grams(item: dict) -> int:
    """
    وزن کل یک ردیف آیتم = وزن یک واحد × تعداد.

    تصمیم (بند ۱۱ DECISIONS.md): `weight_grams` وزن **یک واحد** است، نه وزن کل
    ردیف. دلیل: در همان ردیف، `unit_price` صراحتاً قیمت واحد است و در `quantity`
    ضرب می‌شود؛ `is_bulky` و `category` هم خاصیت یک واحد کالا هستند. بنابراین
    تفسیر سازگار برای `weight_grams` هم «وزن یک واحد» است.
    """
    return item["weight_grams"] * item["quantity"]


# ---------------------------------------------------------------------------
# قاعده‌ی ۶ — کالای حجیم
# ---------------------------------------------------------------------------
def shipment_is_bulky(items: list[dict]) -> bool:
    """
    اگر حتی یک آیتم مرسوله حجیم باشد، کل مرسوله حجیم تلقی می‌شود.

    تصمیم (بند ۱۳ DECISIONS.md): مرسوله واحد فیزیکی ارسال است. آیتم‌های یک
    فروشنده در یک بسته با هم ارسال می‌شوند، پس اگر یکی از آن‌ها حجیم باشد،
    کل بسته باید با ناوگان حجیم برود.
    """
    return any(item["is_bulky"] for item in items)


# ---------------------------------------------------------------------------
# قاعده‌ی ۷ — بازه‌ی شب
# ---------------------------------------------------------------------------
def to_business_timezone(created_at: str) -> datetime:
    """
    رشته‌ی `created_at` را به datetime آگاه‌به‌منطقه و تبدیل‌شده به وقت تهران
    برمی‌گرداند — بند ۱۰ DECISIONS.md.

    اگر رشته آفست نداشته باشد (naive)، فرض می‌شود از قبل به وقت تهران است.
    """
    dt = datetime.fromisoformat(created_at)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=BUSINESS_TZ)
    return dt.astimezone(BUSINESS_TZ)


def is_night_order(created_at: str) -> bool:
    """
    آیا سفارش در بازه‌ی [۲۳:۰۰، ۰۶:۰۰) **به وقت تهران** ثبت شده است؟

    تصمیم (بند ۱۰ DECISIONS.md): همه‌ی زمان‌ها پیش از خواندن ساعت، به وقت تهران
    نرمال می‌شوند. ORD-1013 با آفست `+00:00` ثبت شده و بدون این نرمال‌سازی،
    «ساعت محلیِ فرستنده» خوانده می‌شد، نه ساعتی که ناوگان تحویل ایران در آن
    کار می‌کند.

    مرزها: ۲۳:۰۰ شب حساب می‌شود (شامل)، ۰۶:۰۰ روز حساب می‌شود (غیرشامل)
    — بند ۱۴ DECISIONS.md.
    """
    hour = to_business_timezone(created_at).hour
    return hour >= NIGHT_START_HOUR or hour < NIGHT_END_HOUR


# ---------------------------------------------------------------------------
# قاعده‌ی ۸ — روش پرداخت
# ---------------------------------------------------------------------------
def payment_method_fee(payment_method: str) -> int:
    """
    کارمزد پرداخت در محل.

    تصمیم (بند ۱۲ DECISIONS.md): فقط `online` کارمزد صفر دارد؛ هر مقدار دیگری
    (از جمله مقادیر ناشناخته‌ی احتمالی در آینده) محافظه‌کارانه به‌عنوان پرداخت
    در محل تلقی و مشمول کارمزد می‌شود.
    """
    return 0 if payment_method == ONLINE_PAYMENT_METHOD else CASH_ON_DELIVERY_FEE


# ---------------------------------------------------------------------------
# قاعده‌ی ۵ — مبلغ خالص سفارش
# ---------------------------------------------------------------------------
def items_net_amount(items: list[dict]) -> int:
    """
    مبلغ خالص = Σ (unit_price × quantity − discount).

    تصمیم (بند ۲ DECISIONS.md): مبنا مبلغ **خالص پس از تخفیف** است، نه ناخالص.
    تصمیم (بند ۱۵ DECISIONS.md): `discount` مبلغ تخفیف **کل ردیف** است، نه
    تخفیف هر واحد؛ یعنی در `quantity` ضرب نمی‌شود.
    """
    return sum(
        item["unit_price"] * item["quantity"] - item["discount"] for item in items
    )
